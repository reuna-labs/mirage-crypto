    match pub_of_octets ("\002" ^ x) with
    | Error _ -> Alcotest.(check bool "point parsing" v false)
    | Ok key ->
    let verify = verify_bip340 ~key (r, s) msg in
    Alcotest.(check bool "verified even" v verify);
    match pub_of_octets ("\003" ^ x) with
    | Error _ -> Alcotest.(check bool "point parsing" v false)
